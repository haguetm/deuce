-- The draw seed comes from the server CSPRNG and stays out of clients' reach.
begin;
create extension if not exists pgtap with schema extensions;
select plan(7);

insert into auth.users (id, email) values ('11111111-1111-1111-1111-111111111111', 'u1@test.local');
insert into public.players (wikidata_id, slug, name, sex, rarity)
select 'Q' || (930000000 + t.n * 10 + i), 'seed-' || t.n || '-' || i, 'Seed ' || t.n || '-' || i, 'male', t.tier
from (select tier, row_number() over () as n from unnest(enum_range(null::public.rarity_tier)) tier) t,
     generate_series(1, 2) i;
update public.booster_state set stock = 2 where user_id = '11111111-1111-1111-1111-111111111111';

select ok(pg_get_functiondef('public.open_booster(public.booster_source, text, text)'::regprocedure)
            ~ 'seed bytea := extensions\.gen_random_bytes\(32\)',
  'the seed is generated by gen_random_bytes(32) inside open_booster');
select ok(not has_column_privilege('authenticated', 'public.booster_openings', 'seed', 'SELECT'),
  'authenticated has no SELECT privilege on the seed column');
select ok(not has_column_privilege('anon', 'public.booster_openings', 'seed', 'SELECT'),
  'anon has no SELECT privilege on the seed column');

set local role authenticated;
set local request.jwt.claims = '{"sub":"11111111-1111-1111-1111-111111111111","role":"authenticated"}';
select lives_ok($$select public.open_booster('free', 'seed-test-0001')$$, 'opening works');
select lives_ok($$select public.open_booster('free', 'seed-test-0002')$$, 'second opening works');
select throws_ok('select seed from public.booster_openings', '42501', null, 'the owner cannot read the seed after opening');
reset role;

select ok((select count(distinct seed) = 2 and min(length(seed)) = 32 from public.booster_openings),
  'each opening has its own 32-byte seed');

select * from finish();
rollback;
